  AISA.i18n = {
    locale: 'zh',
    init: async function() {
      // Try to load locale from settings
      if (AISA.storage && AISA.storage.getSettings) {
        const s = await AISA.storage.getSettings();
        if (s.locale) this.locale = s.locale;
      }
    },
    t: function(key) {
      if (this.locale === 'zh' || !key) return key;
      return dict[key] || key;
    },
    applyToDOM: function(root = document) {
      root.querySelectorAll('[data-i18n]').forEach(el => {
        el.innerHTML = this.t(el.getAttribute('data-i18n'));
      });
      root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const translated = this.t(el.getAttribute('data-i18n-placeholder'));
        el.placeholder = translated;
        // contenteditable 元素（如 .cmp-editor）没有原生 placeholder，
        // 占位文本靠 CSS ::before + attr(data-placeholder) 渲染，
        // 必须同步更新 data-placeholder 才会切换语言。
        if (el.hasAttribute('data-placeholder')) {
          el.setAttribute('data-placeholder', translated);
        }
      });
      root.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = this.t(el.getAttribute('data-i18n-title'));
      });
    }
  };

